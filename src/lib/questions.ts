const S = (e: string): Solution => {
  const r = solve(e);
  if (!r.ok) throw new Error(e + ": " + r.error);
  return r;
};
const stepsOf = (r: Solution) => r.steps.map((s) => `${s.expr}   ⟵ ${s.reason}`).concat(`مجموعة الحل: ${r.builder}`);
const place = (correct: string, wrong: string[], i: number) => {
  const w = wrong.filter((x, k) => x !== correct && wrong.indexOf(x) === k).slice(0, 3);
  const pos = i % (w.length + 1);
  const choices = [...w];
  choices.splice(pos, 0, correct);
  return { choices, answer: pos };
};
const rayDistract = (r: Solution, alt: number) => {
  const iv = r.set[0];
  const left = iv.lo === -Infinity;
  const v = left ? iv.hi : iv.lo;
  const c = left ? iv.hiC : iv.loC;
  const op = (l: boolean, cl: boolean) => (l ? (cl ? "≤" : "<") : cl ? "≥" : ">");
  const t = (l: boolean, cl: boolean, x: number) => setText([l ? { lo: -Infinity, hi: x, loC: false, hiC: cl } : { lo: x, hi: Infinity, loC: cl, hiC: false }]);
  void op;
  return [t(!left, c, v), t(left, c, alt), t(!left, c, alt), t(left, !c, v)];
};
const toRay = (r: Solution): Ray => {
  const iv = r.set[0];
  return iv.lo === -Infinity ? { point: iv.hi, closed: iv.hiC, dir: "left" } : { point: iv.lo, closed: iv.loC, dir: "right" };
};

let n = 0;
const qs: Question[] = [];
const id = () => `q${++n}`;

function mcqIneq(level: 1 | 2 | 3, lesson: number, e: string, alt: number, hint: string) {
  const r = S(e);
  const { choices, answer } = place(r.text, rayDistract(r, alt), n);
  qs.push({ id: id(), level, lesson, type: "mcq", prompt: "ما مجموعة حل المتباينة؟", expr: r.original, choices, answer, hint, steps: stepsOf(r) });
}
function mcqSet(level: 1 | 2 | 3, lesson: number, e: string, wrong: string[], hint: string, type: QType = "mcq", prompt = "ما مجموعة حل المتباينة؟") {
  const r = S(e);
  const { choices, answer } = place(r.text, wrong, n);
  qs.push({ id: id(), level, lesson, type, prompt, expr: r.original, choices, answer, hint, steps: stepsOf(r) });
}
function graphQ(level: 1 | 2 | 3, lesson: number, e: string, hint: string) {
  const r = S(e);
  qs.push({ id: id(), level, lesson, type: "graph", prompt: "حلّي المتباينة ثم مثّلي حلها على خط الأعداد (حرّكي النقطة واختاري نوع الدائرة واتجاه السهم).", expr: r.original, target: toRay(r), hint, steps: stepsOf(r) });
}
function orderQ(level: 1 | 2 | 3, lesson: number, e: string, hint: string) {
  const r = S(e);
  const items = r.steps.map((s) => s.expr);
  qs.push({ id: id(), level, lesson, type: "order", prompt: "رتّبي خطوات حل المتباينة من البداية إلى النهاية.", expr: r.original, items, hint, steps: stepsOf(r) });
}
function dragQ(level: 1 | 2 | 3, lesson: number, e: string, hint: string) {
  const r = S(e);
  const iv = r.set[0];
  const left = iv.lo === -Infinity;
  const sym = left ? (iv.hiC ? "≤" : "<") : iv.loC ? "≥" : ">";
  const v = left ? iv.hi : iv.lo;
  const syms = ["<", ">", "≤", "≥"];
  qs.push({ id: id(), level, lesson, type: "drag", prompt: `اسحبي الرمز الصحيح إلى الفراغ:   ${r.original}   ⟸   س ـــ ${ar(v)}`, expr: r.original, choices: syms, answer: syms.indexOf(sym), hint, steps: stepsOf(r) });
}
function custom(q: Omit<Question, "id">, correctIdx = 0) {
  const correct = q.choices![correctIdx];
  const wrong = q.choices!.filter((_, i) => i !== correctIdx);
  const { choices, answer } = place(correct, wrong, n);
  qs.push({ ...q, id: id(), choices, answer });
}

